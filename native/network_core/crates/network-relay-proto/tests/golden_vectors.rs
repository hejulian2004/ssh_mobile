#[test]
fn every_fixture_decodes_matches_manifest_and_round_trips_byte_identical() {
    let manifest = read_manifest();
    let fixtures = manifest["fixtures"].as_array().unwrap();
    assert_eq!(fixtures.len(), EXPECTED_FIXTURE_COUNT);

    for fx in fixtures {
        let file = fx["file"].as_str().unwrap();
        let transport = fx["transport"].as_str().unwrap();
        let expects = &fx["expects"];
        let data = read_fixture(file);

        match transport {
            "control" => {
                let decoded =
                    decode_control(&data).unwrap_or_else(|e| panic!("decode {file}: {e}"));
                assert_control_fixture(&decoded, expects, file);
                let reencoded = encode_frame(&decoded);
                assert_eq!(reencoded, data, "re-encode {file} must be byte-identical");
            }
            "data" => {
                let decoded = decode_data(&data).unwrap_or_else(|e| panic!("decode {file}: {e}"));
                assert_data_fixture(&decoded, expects, file);
                let reencoded = encode_frame(&decoded);
                assert_eq!(reencoded, data, "re-encode {file} must be byte-identical");
            }
            other => panic!("{file}: unknown transport {other:?}"),
        }
    }
}

#[test]
fn framing_negatives() {
    // Too short for the 4-byte length prefix.
    assert!(matches!(
        decode_control(&[0x00, 0x01, 0x02]),
        Err(FrameError::TooShort)
    ));

    // Length prefix mismatch: prefix says 256, actual payload is 2 bytes.
    let bad_prefix = [0x00u8, 0x00, 0x01, 0x00, 0x08, 0x02];
    assert!(matches!(
        decode_control(&bad_prefix),
        Err(FrameError::LengthMismatch {
            prefix: 256,
            actual: 2
        })
    ));

    // Zero prefix with a non-empty payload.
    let mut zero_prefix = vec![0u8; network_relay_proto::FRAME_LENGTH_PREFIX_BYTES];
    zero_prefix.extend_from_slice(&[0x08, 0x02]);
    assert!(matches!(
        decode_control(&zero_prefix),
        Err(FrameError::LengthMismatch {
            prefix: 0,
            actual: 2
        })
    ));

    // Frame exceeds MAX_RELAY_FRAME_BYTES (matching prefix, too-long payload).
    let over_max_body = MAX_RELAY_FRAME_BYTES - network_relay_proto::FRAME_LENGTH_PREFIX_BYTES + 16;
    let mut over =
        Vec::with_capacity(network_relay_proto::FRAME_LENGTH_PREFIX_BYTES + over_max_body);
    over.extend_from_slice(&(over_max_body as u32).to_be_bytes());
    over.resize(
        network_relay_proto::FRAME_LENGTH_PREFIX_BYTES + over_max_body,
        0u8,
    );
    assert!(matches!(
        decode_control(&over),
        Err(FrameError::TooLarge { max: MAX_RELAY_FRAME_BYTES, actual }) if actual == over.len()
    ));

    // Version != 2: well-formed frame with version=1 and no kind.
    let wrong_version = RelayFrame {
        version: 1,
        kind: None,
    };
    let encoded = encode_frame(&wrong_version);
    assert!(matches!(
        decode_control(&encoded),
        Err(FrameError::InvalidVersion {
            version: 1,
            expected: RELAY_V2_VERSION
        })
    ));

    // Unknown oneof tag is tolerated (proto3 skips unknown fields): version=2
    // plus an unknown field 27 (wire type 2). tag == (27<<3)|2 == 218.
    let unknown = [0x08u8, 0x02, 0xda, 0x01, 0x02, 0x00, 0x00];
    let mut with_prefix =
        Vec::with_capacity(network_relay_proto::FRAME_LENGTH_PREFIX_BYTES + unknown.len());
    with_prefix.extend_from_slice(&(unknown.len() as u32).to_be_bytes());
    with_prefix.extend_from_slice(&unknown);
    let decoded = decode_control(&with_prefix).expect("unknown oneof tag is tolerated");
    assert_eq!(decoded.version, RELAY_V2_VERSION);
    assert!(
        decoded.kind.is_none(),
        "unknown oneof tag leaves kind unset"
    );

    // Same tolerances hold on the data route; a versionless data frame decodes.
    let data = RelayDataFrame {
        version: RELAY_V2_VERSION,
        kind: None,
    };
    let data_encoded = encode_frame(&data);
    let decoded_data = decode_data(&data_encoded).expect("data frame decode");
    assert_eq!(decoded_data.version, RELAY_V2_VERSION);
}
