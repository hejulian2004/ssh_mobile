#[test]
fn manifest_covers_exactly_the_bin_files_on_disk() {
    use walkdir::WalkDir;
    let dir = Path::new(FIXTURES_DIR);
    assert!(dir.is_dir(), "fixtures dir missing at {FIXTURES_DIR}");
    let manifest = read_manifest();
    let manifest_files: BTreeSet<String> = manifest["fixtures"]
        .as_array()
        .unwrap()
        .iter()
        .map(|fx| fx["file"].as_str().unwrap().to_string())
        .collect();
    assert_eq!(manifest_files.len(), EXPECTED_FIXTURE_COUNT);
    let on_disk: BTreeSet<String> = WalkDir::new(dir)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|e| e.file_type().is_file() && e.path().extension().is_some_and(|x| x == "bin"))
        .filter_map(|e| {
            e.path()
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
        })
        .collect();
    assert_eq!(on_disk.len(), EXPECTED_FIXTURE_COUNT);
    assert_eq!(
        manifest_files, on_disk,
        "manifest fixture set must equal the .bin files on disk"
    );
}

