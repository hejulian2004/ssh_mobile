//! Golden-vector tests against `protocol/relay_v2_testdata/`.
//!
//! For every fixture in the manifest: read the full wire frame (4-byte BE
//! length prefix + protobuf), decode it, assert every semantic expectation
//! from `manifest.json`, re-encode it, and assert the result is byte-identical
//! to the original file. Also covers the framing negatives (bad length prefix,
//! length mismatch, over max, version != 2, unknown oneof tag tolerated).
//!
//! The fixtures live outside the crate tree (relative path from this crate's
//! root: `../../../../protocol/relay_v2_testdata`); a dedicated test asserts
//! the directory exists to keep that cross-crate path honest.

use std::collections::BTreeSet;
use std::path::Path;

use network_relay_proto::{
    decode_control, decode_data, encode_frame, relay_data_frame, relay_frame, ErrorCode,
    FrameError, RealtimeSignalKind, RelayDataFrame, RelayFrame, ResolveStatus, RuntimeEpoch,
    TransportCapability, MAX_RELAY_FRAME_BYTES, RELAY_V2_VERSION,
};
use serde_json::Value;

/// Repository-root-relative fixture directory, resolved from the crate root.
const FIXTURES_DIR: &str = "../../../../protocol/relay_v2_testdata";
/// Number of `.bin` full-wire fixtures generated by `generate_fixtures.py`.
const EXPECTED_FIXTURE_COUNT: usize = 23;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn read_manifest() -> Value {
    let path = format!("{FIXTURES_DIR}/manifest.json");
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {path}: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {path}: {e}"))
}

fn read_fixture(file: &str) -> Vec<u8> {
    let path = format!("{FIXTURES_DIR}/{file}");
    std::fs::read(&path).unwrap_or_else(|e| panic!("read {path}: {e}"))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn s<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("expected string field {key:?}"))
}

fn u64_val(v: &Value, key: &str) -> u64 {
    v.get(key)
        .and_then(Value::as_u64)
        .unwrap_or_else(|| panic!("expected u64 field {key:?}"))
}

fn u32_val(v: &Value, key: &str) -> u32 {
    u64_val(v, key) as u32
}

fn i64_val(v: &Value, key: &str) -> i64 {
    v.get(key)
        .and_then(Value::as_i64)
        .unwrap_or_else(|| panic!("expected i64 field {key:?}"))
}

fn i32_val(v: &Value, key: &str) -> i32 {
    u64_val(v, key) as i32
}

fn bool_val(v: &Value, key: &str) -> bool {
    v.get(key)
        .and_then(Value::as_bool)
        .unwrap_or_else(|| panic!("expected bool field {key:?}"))
}

fn assert_epoch(epoch: &RuntimeEpoch, expects: &Value) {
    assert_eq!(format!("0x{:08x}", epoch.high), s(expects, "epoch_high"));
    assert_eq!(format!("0x{:08x}", epoch.low), s(expects, "epoch_low"));
}

